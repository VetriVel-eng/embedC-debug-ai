export async function analyzeCode(
  code: string,
  language: Language,
  _options?: AnalysisOptions
): Promise<AnalysisResult> {
  const trimmed = code.trim();

  if (!trimmed) {
    throw new Error(
      'Please enter some C or Embedded C code before analyzing.'
    );
  }

  const response = await fetch('http://127.0.0.1:8000/analyze', {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      code,
      language,
    }),
  });

  if (!response.ok) {
    throw new Error(`Backend error: ${response.status}`);
  }

  const data = await response.json();

  if (!data.analysis) {
    throw new Error('No analysis received from AI backend.');
  }

  const aiText = data.analysis;

  // Extract improved code from Gemini response
  const codeMatch = aiText.match(
    /(?:Improved Corrected Code|Improved Code|Corrected Code)[\s\S]*?```(?:c|cpp|C)?\s*([\s\S]*?)```/i
  );

  const improvedCode = codeMatch?.[1]?.trim() || code;

  // Create analysis issue
  const issue: AnalysisIssue = {
    id: `ai-analysis-${Date.now()}`,
    type: 'AI Code Analysis',
    severity: 'suggestion',
    line: 1,
    message: aiText,
    cause: 'Analysis generated by Gemini AI.',
    suggestion:
      'Review the AI explanation and corrected code before using it.',
    codeSnippet: code,
  };

  return {
    id: `analysis-${Date.now()}`,

    timestamp: new Date().toLocaleDateString('en-US', {
      month: 'short',
      day: 'numeric',
      year: 'numeric',
      hour: '2-digit',
      minute: '2-digit',
    }),

    name: 'AI Code Analysis',

    language,

    summary: 'Gemini AI analyzed the submitted code.',

    status: 'warning',

    issuesCount: {
      errors: 0,
      warnings: 0,
      suggestions: 1,
    },

    issues: [issue],

    originalCode: code,

    improvedCode,

    diffExplanation:
      'Gemini AI generated the analysis and suggested corrected code.',

    tip:
      'AI-generated suggestions should be reviewed and tested before use in production systems.',
  };
}


// Backend connection test
export async function testBackendConnection(
  endpointUrl: string
): Promise<{ success: boolean; message: string }> {
  try {
    const response = await fetch(endpointUrl);

    if (!response.ok) {
      return {
        success: false,
        message: `Backend returned status ${response.status}.`,
      };
    }

    return {
      success: true,
      message: 'Backend connection successful.',
    };
  } catch (error) {
    console.error('Backend connection failed:', error);

    return {
      success: false,
      message: 'Unable to connect to the backend service.',
    };
  }
}